"""Generates web/assets.js (frog sprites, food icons, button glyphs) from the sources the phone widget already uses, so the art is drawn once.
    python web/build_assets.py"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
sprites = json.loads((ROOT / "android/assets/tadpole.json").read_text())
java = (ROOT / "android/src/app/tadpole/widget/Pixel.java").read_text()
colors = {m.group(1): "#" + m.group(2).upper() for m in re.finditer(r"case '(.)': return 0xFF([0-9A-Fa-f]{6});", java)}
foods = [re.findall(r'"([^"]*)"', b) for b in re.findall(r"\{([^{}]*)\}", re.search(r"FOODS = \{(.*?)\};", java, re.S).group(1))]
glyphs = {n.lower(): re.findall(r'"([^"]*)"', re.search(rf"G_{n} = \{{(.*?)\}};", java, re.S).group(1)) for n in ("STOOL", "BRAIN", "MEAL", "CHECK", "X")}
assert len(foods) == 7 and all(len(f) == 8 for f in foods) and all(len(g) == 8 for g in glyphs.values())
out = {"w": sprites["w"], "h": sprites["h"], "stages": sprites["stages"], "palettes": sprites["palettes"], "foods": foods, "foodColors": colors, "glyphs": glyphs}
(ROOT / "web/assets.js").write_text("/* generated by build_assets.py: do not edit */\nwindow.TadpoleAssets = " + json.dumps(out, separators=(",", ":")) + ";\n")
print("assets.js", len((ROOT / "web/assets.js").read_text()), "bytes;", len(foods), "foods;", sorted(glyphs))
